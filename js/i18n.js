(function () {
  var nav = document.querySelector('.idiomas');
  var botones = nav ? nav.querySelectorAll('[data-lang]') : [];

  function aplicar(lang) {
    var t = window.I18N[lang] || window.I18N.es;
    document.documentElement.lang = t._lang;
    document.documentElement.dir = t._dir;
    document.documentElement.setAttribute('data-lang', lang);
    if (!document.documentElement.hasAttribute('data-keep-title')) document.title = t._title;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (!(k in t)) return;
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = t[k];
      else el.textContent = t[k];
    });
    botones.forEach(function (b) {
      b.classList.toggle('is-active', b.getAttribute('data-lang') === lang);
    });
    window.LANG = lang;
    document.querySelectorAll('[data-src-es]').forEach(function (img) {
      var src = img.getAttribute('data-src-' + lang) || img.getAttribute('data-src-es');
      if (img.getAttribute('src') !== src) img.setAttribute('src', src);
    });
    document.querySelectorAll('a[data-keep-lang]').forEach(function (a) {
      a.href = a.getAttribute('data-keep-lang') + '?lang=' + lang;
    });
    try { localStorage.setItem('md-lang', lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  // Prioridad: ?lang= en la URL > elección guardada > idioma del navegador > español
  var param = (location.search.match(/[?&]lang=(es|pt|he)/) || [])[1];
  param = param || document.documentElement.getAttribute('data-lang-default');
  var guardado = null;
  try { guardado = localStorage.getItem('md-lang'); } catch (e) {}
  var nav_lang = (navigator.language || '').toLowerCase();
  var auto = nav_lang.indexOf('pt') === 0 ? 'pt' : nav_lang.indexOf('he') === 0 ? 'he' : 'es';
  aplicar(param || guardado || auto);

  botones.forEach(function (b) {
    b.addEventListener('click', function () {
      var lang = b.getAttribute('data-lang');
      aplicar(lang);
      if (history.replaceState) {
        history.replaceState(null, '', location.pathname + '?lang=' + lang + location.hash);
      }
    });
  });
})();
